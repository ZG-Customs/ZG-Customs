CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL,
    oidc_issuer VARCHAR(255) NOT NULL,
    oidc_subject VARCHAR(255) NOT NULL,

    CONSTRAINT uq_users_oidc_identity UNIQUE (oidc_issuer, oidc_subject)
);

CREATE TABLE IF NOT EXISTS roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL
);

INSERT INTO roles (code, name) VALUES
    ('CLIENT', 'Client / vehicle owner'),
    ('MECHANIC', 'Mechanic'),
    ('WORKSHOP_MANAGER', 'Workshop manager'),
    ('ADMIN', 'Platform administrator')
ON CONFLICT (code) DO NOTHING;


CREATE TABLE IF NOT EXISTS user_roles (
    user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL
        REFERENCES roles(id) ON DELETE RESTRICT,

    PRIMARY KEY (user_id, role_id)
);


CREATE TABLE IF NOT EXISTS workshops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manager_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
    name VARCHAR(150) NOT NULL
);


CREATE TABLE IF NOT EXISTS workshop_memberships (
    workshop_id BIGINT NOT NULL REFERENCES workshops(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (workshop_id, user_id)
);


CREATE TABLE IF NOT EXISTS vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    registration VARCHAR(32) NOT NULL,
    make VARCHAR(100) NOT NULL,
    model VARCHAR(100) NOT NULL,
    production_year INTEGER NOT NULL,
    mileage INTEGER NOT NULL CHECK (mileage >= 0),
    archived_at TIMESTAMPTZ NULL
);


CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id) ON DELETE RESTRICT,
    workshop_id BIGINT NOT NULL REFERENCES workshops(id) ON DELETE RESTRICT,
    service_type_id BIGINT NOT NULL REFERENCES service_types(id) ON DELETE RESTRICT,
    requested_at TIMESTAMPTZ NOT NULL,
    confirmed_at TIMESTAMPTZ NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'REQUESTED',
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT ck_bookings_status CHECK (
        status IN ('REQUESTED', 'AWAITING_OWNER', 'CONFIRMED', 'REJECTED', 'CANCELLED')
    ),
    CONSTRAINT ck_bookings_version CHECK (version >= 0)
);


CREATE TABLE IF NOT EXISTS appointment_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id) ON DELETE RESTRICT,
    proposed_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',

    CONSTRAINT ck_appointment_proposals_status CHECK (
        status IN ('PENDING', 'ACCEPTED', 'REJECTED')
    )
);


CREATE INDEX IF NOT EXISTS idx_user_roles_role_id
    ON user_roles (role_id);
CREATE INDEX IF NOT EXISTS idx_workshop_memberships_user_id
    ON workshop_memberships (user_id);


CREATE INDEX IF NOT EXISTS idx_vehicles_owner_id
    ON vehicles (owner_id);
CREATE INDEX IF NOT EXISTS idx_bookings_vehicle_id
    ON bookings (vehicle_id);
CREATE INDEX IF NOT EXISTS idx_bookings_workshop_requested_at
    ON bookings (workshop_id, requested_at);
CREATE INDEX IF NOT EXISTS idx_bookings_service_type_id
    ON bookings (service_type_id);
CREATE INDEX IF NOT EXISTS idx_appointment_proposals_booking_id
    ON appointment_proposals (booking_id);

-- Account registration and workshop approvals.
ALTER TABLE users
    ADD COLUMN status varchar(16) NOT NULL DEFAULT 'UNREGISTERED'
        CHECK (status IN ('UNREGISTERED', 'PENDING', 'ACTIVE', 'DEACTIVATED')),
    ADD COLUMN contact_details text,
    ADD COLUMN specializations text;

UPDATE users SET status = 'ACTIVE'
WHERE EXISTS (SELECT 1 FROM user_roles WHERE user_id = users.id);

-- Onboarding assigns one application role per account.
CREATE UNIQUE INDEX uq_user_roles_user_id ON user_roles (user_id);

CREATE TABLE workshop_applications (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    applicant_id bigint NOT NULL REFERENCES users(id),
    name varchar(150) NOT NULL,
    contact_details text NOT NULL,
    ownership_evidence varchar(2000) NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED')),
    decided_at timestamptz
);

CREATE UNIQUE INDEX one_pending_application ON workshop_applications (applicant_id)
    WHERE status = 'PENDING';

ALTER TABLE workshops
    ADD COLUMN application_id bigint UNIQUE REFERENCES workshop_applications(id),
    ADD COLUMN contact_details text,
    ADD COLUMN status varchar(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DEACTIVATED'));

CREATE TABLE membership_requests (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    workshop_id bigint NOT NULL REFERENCES workshops(id),
    status varchar(16) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'REMOVED')),
    requested_at timestamptz NOT NULL DEFAULT now(),
    ended_at timestamptz
);

CREATE UNIQUE INDEX one_current_membership ON membership_requests (user_id)
    WHERE status IN ('PENDING', 'ACCEPTED');

INSERT INTO membership_requests (user_id, workshop_id, status)
SELECT user_id, workshop_id, 'ACCEPTED' FROM workshop_memberships;

CREATE UNIQUE INDEX one_active_workshop_per_user ON workshop_memberships (user_id);
