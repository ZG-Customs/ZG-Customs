BEGIN;

CREATE TABLE IF NOT EXISTS service_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500) NOT NULL
);

INSERT INTO service_types (code, name, description) VALUES
    ('REGULAR_SERVICE', 'Redovni servis', 'Redovno održavanje vozila.'),
    ('TIRE_CHANGE', 'Zamjena guma', 'Zamjena i balansiranje guma.'),
    ('BRAKE_REPAIR', 'Popravak kočnica', 'Pregled i popravak kočnog sustava.'),
    ('DIAGNOSTICS', 'Dijagnostika', 'Dijagnostika kvarova na vozilu.')
ON CONFLICT (code) DO NOTHING;


CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL,
    oidc_issuer VARCHAR(255) NOT NULL,
    oidc_subject VARCHAR(255) NOT NULL,

    CONSTRAINT uq_users_oidc_identity
        UNIQUE (oidc_issuer, oidc_subject)
);


CREATE TABLE IF NOT EXISTS roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL
);

INSERT INTO roles (code, name) VALUES
    ('CLIENT', 'Client / vehicle owner'),
    ('MECHANIC', 'Mechanic'),
    ('WORKSHOP_MANAGER', 'Workshop manager'),
    ('ADMIN', 'Platform administrator')
ON CONFLICT (code) DO NOTHING;


CREATE TABLE IF NOT EXISTS user_roles (
    user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL
        REFERENCES roles(id) ON DELETE RESTRICT,

    PRIMARY KEY (user_id, role_id)
);


CREATE TABLE IF NOT EXISTS workshops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manager_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
    name VARCHAR(150) NOT NULL
);


CREATE TABLE IF NOT EXISTS workshop_memberships (
    workshop_id BIGINT NOT NULL REFERENCES workshops(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (workshop_id, user_id)
);


CREATE TABLE IF NOT EXISTS vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    registration VARCHAR(32) NOT NULL,
    make VARCHAR(100) NOT NULL,
    model VARCHAR(100) NOT NULL,
    production_year INTEGER NOT NULL,
    mileage INTEGER NOT NULL CHECK (mileage >= 0),
    archived_at TIMESTAMPTZ NULL
);


CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id) ON DELETE RESTRICT,
    workshop_id BIGINT NOT NULL REFERENCES workshops(id) ON DELETE RESTRICT,
    service_type_id BIGINT NOT NULL REFERENCES service_types(id) ON DELETE RESTRICT,
    requested_at TIMESTAMPTZ NOT NULL,
    confirmed_at TIMESTAMPTZ NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'REQUESTED',
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT ck_bookings_status CHECK (
        status IN ('REQUESTED', 'AWAITING_OWNER', 'CONFIRMED', 'REJECTED', 'CANCELLED')
    ),
    CONSTRAINT ck_bookings_version CHECK (version >= 0)
);


CREATE TABLE IF NOT EXISTS appointment_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id) ON DELETE RESTRICT,
    proposed_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',

    CONSTRAINT ck_appointment_proposals_status CHECK (
        status IN ('PENDING', 'ACCEPTED', 'REJECTED')
    )
);


CREATE INDEX IF NOT EXISTS idx_user_roles_role_id
    ON user_roles (role_id);
CREATE INDEX IF NOT EXISTS idx_workshop_memberships_user_id
    ON workshop_memberships (user_id);


CREATE INDEX IF NOT EXISTS idx_vehicles_owner_id
    ON vehicles (owner_id);
CREATE INDEX IF NOT EXISTS idx_bookings_vehicle_id
    ON bookings (vehicle_id);
CREATE INDEX IF NOT EXISTS idx_bookings_workshop_requested_at
    ON bookings (workshop_id, requested_at);
CREATE INDEX IF NOT EXISTS idx_bookings_service_type_id
    ON bookings (service_type_id);
CREATE INDEX IF NOT EXISTS idx_appointment_proposals_booking_id
    ON appointment_proposals (booking_id);

COMMIT;